#!/usr/bin/env node
/**
 * Pull the contract bindings from the sibling contracts repo.
 *
 *   npm run sync:contracts
 *
 * Copies, from ../scs-ethcali/frontend:
 *   abis/*.json      every ABI the contracts repo exports (extra ABIs that live
 *                    only here — ERC20, the Durin registrar — are left alone)
 *   addresses.json   per-network deployed addresses
 *   contracts.ts     the `as const` bundle: CONTRACTS + ADDRESSES
 *
 * and writes:
 *   frontend/abis/swag.ts            `swag1155Abi` as a typed `as const` array.
 *                                    The Swag1155 collection is a clone, so it
 *                                    has no entry in ADDRESSES/CONTRACTS; this is
 *                                    what lets viem type-check every swag call.
 *   frontend/swag-collection.json    the live collection on Base, read from
 *                                    deployments/base-latest.json
 *   frontend/CONTRACTS_SOURCE.json   { repo, commit, generatedAt } so a stale
 *                                    copy can be traced to the commit it came from
 *
 * The copies are committed so Vercel builds without the sibling checkout.
 * Never hand-edit the outputs; re-run this instead.
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const walletRoot = path.resolve(here, '..');
const contractsRoot = path.resolve(walletRoot, '..', 'scs-ethcali');
const srcFrontend = path.join(contractsRoot, 'frontend');
const dstFrontend = path.join(walletRoot, 'frontend');

const SWAG_COLLECTION_NAME = 'ETHCALI-SWAG-2026';
const SWAG_CHAIN_ID = 8453;

function fail(message) {
  console.error(`sync-contracts: ${message}`);
  process.exit(1);
}

if (!fs.existsSync(srcFrontend)) {
  fail(`${srcFrontend} not found — clone ETHcali/scs-ethcali next to this repo first`);
}

// ── ABIs ────────────────────────────────────────────────────────────────────
const srcAbis = path.join(srcFrontend, 'abis');
const dstAbis = path.join(dstFrontend, 'abis');
fs.mkdirSync(dstAbis, { recursive: true });

const abiFiles = fs.readdirSync(srcAbis).filter((f) => f.endsWith('.json'));
if (abiFiles.length === 0) fail(`no ABI files in ${srcAbis}`);
for (const file of abiFiles) {
  fs.copyFileSync(path.join(srcAbis, file), path.join(dstAbis, file));
}

// ── addresses.json + contracts.ts ───────────────────────────────────────────
for (const file of ['addresses.json', 'contracts.ts']) {
  const src = path.join(srcFrontend, file);
  if (!fs.existsSync(src)) fail(`${src} missing — run \`npm run setup:frontend\` in scs-ethcali`);
  fs.copyFileSync(src, path.join(dstFrontend, file));
}

// ── Typed Swag1155 ABI ──────────────────────────────────────────────────────
const swagAbiPath = path.join(dstAbis, 'Swag1155.json');
const swagAbi = JSON.parse(fs.readFileSync(swagAbiPath, 'utf8'));
if (!Array.isArray(swagAbi)) fail('Swag1155.json is not a bare ABI array');

const swagTs = `// GENERATED by scripts/sync-contracts.mjs from frontend/abis/Swag1155.json.
// Do not edit. \`as const\` is the point: viem infers every function name,
// argument tuple and return type from this literal, so a hook that calls a
// function the contract no longer has fails \`npm run typecheck\`.
export const swag1155Abi = ${JSON.stringify(swagAbi, null, 2)} as const;
`;
fs.writeFileSync(path.join(dstAbis, 'swag.ts'), swagTs);

// ── Live swag collection on Base ────────────────────────────────────────────
const deploymentPath = path.join(contractsRoot, 'deployments', 'base-latest.json');
if (!fs.existsSync(deploymentPath)) fail(`${deploymentPath} missing`);
const deployment = JSON.parse(fs.readFileSync(deploymentPath, 'utf8'));
const collectionAddress = deployment?.swagCollections?.[SWAG_COLLECTION_NAME];
if (!/^0x[0-9a-fA-F]{40}$/.test(String(collectionAddress ?? ''))) {
  fail(`deployments/base-latest.json has no swagCollections["${SWAG_COLLECTION_NAME}"]`);
}

fs.writeFileSync(
  path.join(dstFrontend, 'swag-collection.json'),
  JSON.stringify(
    {
      name: SWAG_COLLECTION_NAME,
      chainId: SWAG_CHAIN_ID,
      address: collectionAddress,
      factory: deployment.swagFactory ?? null,
      deployedAt: deployment.timestamp ?? null,
    },
    null,
    2
  ) + '\n'
);

// ── Provenance ──────────────────────────────────────────────────────────────
let commit = 'unknown';
try {
  commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: contractsRoot, encoding: 'utf8' }).trim();
} catch {
  console.warn('sync-contracts: could not read the scs-ethcali commit (not a git checkout?)');
}

fs.writeFileSync(
  path.join(dstFrontend, 'CONTRACTS_SOURCE.json'),
  JSON.stringify(
    { repo: 'ETHcali/scs-ethcali', commit, generatedAt: new Date().toISOString() },
    null,
    2
  ) + '\n'
);

console.log(
  `sync-contracts: ${abiFiles.length} ABIs, addresses.json, contracts.ts, abis/swag.ts, ` +
    `swag-collection.json (${collectionAddress}) from ${commit.slice(0, 12)}`
);
